def seuils_vagues(age):
    """Progression a partir de laquelle chaque vague s'ouvre (vague 2 a 5)."""
    a, b = ETAPES_SITU[age]
    return [int(round(a + (b - a) * f)) for f in (0.2, 0.4, 0.6, 0.8)]


