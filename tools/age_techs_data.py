# ---------------------------------------------------------------- echelle
# 16/08 - LE CUMUL. Retour de cooldude808 sur le Workshop :
#
#   « buffs stack from technologies so much that you basically become a one
#     planet fallen empire. make debuffs bigger or buffs smaller so that when
#     you finish with the whole pre ftl thing you will be where the game
#     actually starts »
#
# Personne n'avait additionne la colonne. Cumul des cent technologies, valeurs
# d'origine :
#
#   production des emplois, toutes ressources  +635 %
#   vitesse de recherche                       +185 %
#   nourriture +134 %   croissance +129 %   energie +105 %
#   unite       +96 %   stabilite  +71 points   bonheur +49 %
#
# Les penalites d'etape, elles, s'effacent en montant et disparaissent a
# l'emergence : il n'y a donc AUCUN contrepoids a l'arrivee. Un empire qui perce
# sortait avec six fois la production d'un empire neuf, et 71 points de
# stabilite sur une echelle qui plafonne a 100. « One planet fallen empire »
# etait exact.
#
# Chaque technologie garde sa valeur d'origine dans la table ci-dessous - c'est
# elle qui dit l'intention, et elle reste lisible. L'echelle est appliquee a la
# sortie, en un seul endroit, pour qu'un reglage futur soit un chiffre a changer
# et non cent lignes a reecrire.
#
# A 0,20 le cumul devient : emplois +127 %, recherche +37 %, stabilite +14,
# bonheur +10 %. Un empire qui emerge est en avance, pas hors categorie - et
# l'Heritage de l'Ascension redevient ce qu'il devait etre, la seule vraie
# recompense permanente du chemin.
# 1.3 : on passe de 100 a 250 technologies. A echelle constante le cumul
# repasserait de +127 % a plus de +300 % de production - exactement le defaut
# que cooldude808 avait signale et qu'on venait de corriger. L'echelle suit donc
# le nombre : 0.20 x (100/250) = 0.08.
ECHELLE_MODS = 0.08


def _mise_a_l_echelle(mods):
    return {k: round(v * ECHELLE_MODS, 3) for k, v in mods.items()}



